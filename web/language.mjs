const photos = count => count === 1 ? 'photo' : 'photos';
const folders = count => count === 1 ? 'folder' : 'folders';
const storageKey = 'photo-location-language';

export function savedLanguage() {
  try {
    if (localStorage.getItem(storageKey) === 'en') return 'en';
  } catch {
    // The language can still be changed when browser storage is unavailable.
  }
  return 'zh-CN';
}

export function saveLanguage(language) {
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    // The current page still uses the selected language.
  }
}

export function translate(language, key, ...args) {
  const dictionary = messages[language];
  const message = Object.hasOwn(dictionary, key) ? dictionary[key] : dictionary.requestFailed;
  return typeof message === 'function' ? message(...args) : message;
}
